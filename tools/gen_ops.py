    lines.extend([
        "        default: return \"Cell_Unknown\";",
        "    }",
        "}",
        "",
        "inline CellType cell_type_from_string(std::string_view name) {"
    ])

    for c in cells:
        lines.append(f"    if (name == \"{c['str_name']}\") return CellType::{c['name']};")

