        "    Unsupported,  // no native strict cell-kernel execution",
        "    Implemented,  // strict shared cell kernel only; graph executors remain separate",
        "};",
        "",
        "struct ResetMetadata {",
        "    ResetAction state_value;",
        "    ResetAction aux_state;",
        "    ResetAction previous_input;",
        "    ResetAction delay_buffer;",
        "    ResetAction delay_index;",
        "    ResetAction latch_state;",
        "    ResetAction activation_count;",
        "    ResetAction output_value;",
        "};",
        "",
        "struct ParameterDescriptor {",
        "    const char* name;",
        "    ParameterSlot slot;",
        "    ParameterKind kind;",
        "    ParameterValueType value_type;",
        "    const char* legacy_mapping;",
        "    double search_min;",
        "    double search_max;",
        "    bool has_search_domain;",
        "    bool finite_only;",
        "    bool trainable_continuous;",
        "};",
        "",
        "struct CellContract {",
        "    CellType type;",
        "    uint8_t code;",
        "    const char* name;",
        "    uint8_t input_port_count;",
        "    const char* input_semantics;",
        "    const char* output_contract;",
        "    uint8_t mapped_opcode;",
        "    PrimitiveBounds mapped_bounds;",
        "    ExecutionPolicy execution_policy;",
        "    std::array<ParameterDescriptor, 2> parameters;",
        "    std::array<StateField, 2> state_fields;",
        "    uint8_t state_field_count;",
        "    InitializationDependency initialization_dependency;",
        "    const char* first_step_semantics;",
        "    bool legacy_state_dependency;",
        "    ResetMetadata reset;",
        "    SemanticProfile semantic_profile;",
        "    uint32_t semantic_version;",
        "    StrictExecutionStatus strict_execution;",
        "    VjpCapability vjp_capability;",
        "};",
        "",
        "struct ContinuousValue {",
        "    double value;",
        "};",
        "struct ChannelIndex {",
        "    std::size_t value;",
        "    explicit constexpr ChannelIndex(std::size_t v) : value(v) {}",
        "};",
        "struct DelayTicks {",
        "    uint64_t value;",
        "    explicit constexpr DelayTicks(uint64_t v) : value(v) {}",
        "};",
        "enum class MinMaxMode : uint8_t { Min = 0, Max = 1 };",
        "struct UnusedParameter {};",
        "using ParameterValue = std::variant<ContinuousValue, ChannelIndex, DelayTicks, MinMaxMode, UnusedParameter>;",
        "struct ContinuousParameterList {",
        "    std::array<ParameterSlot, 2> slots{};",
        "    uint8_t count = 0;",
        "};",
        "",
        "inline constexpr ParameterValue parameter_value_for_channel(ChannelIndex value) { return value; }",
        "inline constexpr ParameterValue parameter_value_for_delay(DelayTicks value) { return value; }",
        "inline constexpr ParameterValue parameter_value_for_continuous(ContinuousValue value) { return value; }",
        "",
        "inline std::span<const CellContract> all_cell_contracts();",
        "",
        "inline const CellContract* find_cell_contract(uint8_t code) {",
        "    for (const auto& contract : all_cell_contracts()) {",
        "        if (contract.code == code) return &contract;",
        "    }",
        "    return nullptr;",
        "}",
        "",
        "inline std::optional<std::reference_wrapper<const CellContract>> contract_for(CellType type) {",
        "    for (const auto& contract : all_cell_contracts()) {",
        "        if (contract.type == type) return std::cref(contract);",
        "    }",
        "    return std::nullopt;",
        "}",
        "",
        "inline std::optional<std::reference_wrapper<const CellContract>> contract_for_code(uint8_t code) {",
        "    if (const auto* contract = find_cell_contract(code)) return std::cref(*contract);",
        "    return std::nullopt;",
        "}",
        "",
        "inline std::optional<std::reference_wrapper<const CellContract>> contract_for_code(",
        "    uint8_t code, uint8_t profile_code) {",
        "    if (!semantic_profile_from_code(profile_code)) return std::nullopt;",
        "    return contract_for_code(code);",
        "}",
        "",
        "inline std::optional<std::reference_wrapper<const CellContract>> contract_for_code(",
