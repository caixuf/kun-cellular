            "        const double ds1 = next_aux;",
            "        const double ds2 = mu * (1.0 - next_state * next_state) * next_aux -",
            "            next_state + in0;",
            "        const double raw_next_state = next_state + ds1 * dt;",
            "        const double raw_next_aux = next_aux + ds2 * dt;",
            "        if (strict && (!isfinite(ds1) || !isfinite(ds2) ||",
            "            !isfinite(raw_next_state) || !isfinite(raw_next_aux)))",
            "            return SDSC_CELL_KERNEL_NUMERICAL_ERROR;",
            "        next_state = sdsc_cell_kernel_clamp_double(raw_next_state, -10.0, 10.0);",
