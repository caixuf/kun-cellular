def load_ops_spec():
    with open(OPS_YAML_PATH, "r", encoding="utf-8") as f:
        spec = yaml.safe_load(f)
    return spec

def generate_c11_header(spec):
    prims = spec["sdsc_primitives"]
    lines = [
        AUTO_GEN_BANNER,
        "#ifndef KUN_CELLULAR_SDSC_PRIMITIVES_H_",
        "#define KUN_CELLULAR_SDSC_PRIMITIVES_H_",
        "",
        "#include <math.h>",
        "#include <stdint.h>",
        "",
        "#if defined(__GNUC__) || defined(__clang__)",
        "#define SDSC_INLINE static inline __attribute__((always_inline))",
        "#else",
        "#define SDSC_INLINE static inline",
        "#endif",
        "",
        "/* 27 大完备原子计算原语类型枚举 (5-bit 紧凑硬件操作码) */",
        "typedef enum {"
    ]

    for i, p in enumerate(prims):
        sep = "," if i < len(prims) - 1 else ""
        lines.append(f"    {p['name']:<24} = {p['id']}{sep}   /* {p['description']} */")

    lines.extend([
        "} SdscOpType;",
        "",
        "/**",
        " * 核心原语单步前向推演函数 (无堆分配、纯浮点寄存器、李雅普诺夫有界保证)",
        " * ",
        " * @param op_type  原语算子枚举",
        " * @param g        可演化增益参数 (gain)",
        " * @param x        当前输入突触加权和",
        " * @param state    细胞私有累积状态槽 1 (指针，原位读写)",
        " * @param aux      细胞私有辅助状态槽 2 (指针，原位读写)",
        " * @return float   本拍单步激发输出 u(t)",
        " */",
        "SDSC_INLINE float sdsc_primitive_eval(",
        "    uint8_t op_type,",
        "    float g,",
        "    float x,",
        "    float* state,",
        "    float* aux",
        ") {",
        "    float out = 0.0f;",
        "    float s = *state;",
        "    float a = *aux;",
        "",
        "    switch (op_type) {"
    ])

    for p in prims:
        lines.append(f"        case {p['name']}: {{ // opcode {p['id']}")
        eval_body = str(p['eval_code']).strip()
        for b_line in eval_body.splitlines():
            lines.append(f"            {b_line}")
        lines.append("            break;")
        lines.append("        }")

    lines.extend([
        "        default:",
        "            out = x;",
        "            break;",
        "    }",
        "",
        "    *state = s;",
        "    *aux   = a;",
        "    return out;",
        "}",
        "",
        "/* 包含全图反向伴随方程与直通梯度 (VJP) 算子头文件 */",
        '#include "sdsc_primitives_vjp.h"',
        "",
        "#endif /* KUN_CELLULAR_SDSC_PRIMITIVES_H_ */",
        ""
    ])
    return "\n".join(lines)

