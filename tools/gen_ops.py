        "            strict, &primitive_valid);",
        "        if (strict && !primitive_valid)",
        "            return SDSC_CELL_KERNEL_NUMERICAL_ERROR;",
        "        if (!strict) {",
        "            if (!isfinite(s)) s = 0.0f;",
        "            if (!isfinite(out)) out = 0.0f;",
        "        } else if (!isfinite(s) || !isfinite(a) || !isfinite(out)) {",
